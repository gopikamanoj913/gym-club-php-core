<?php
// Initialize variables for form data
$name = $email = $gym = $comment = "";
$error = $success = "";

// Database connection settings (update with your credentials)
$host = "localhost";   // Database host (usually localhost)
$dbname = "mca23"; // Database name
$username = "root"; // Database username
$password = ""; // Database password

// Create a database connection
$conn = new mysqli($host, $username, $password, $dbname);

// Check connection
if ($conn->connect_error) {
    die("Connection failed: " . $conn->connect_error);
}

// Check if the form has been submitted
if ($_SERVER["REQUEST_METHOD"] == "POST") {
    // Get the form data from POST request and sanitize input
    $name = htmlspecialchars(trim($_POST['name']));
    $email = htmlspecialchars(trim($_POST['email']));
    $gym = htmlspecialchars(trim($_POST['gym'])); // Added gym field
    $comment = htmlspecialchars(trim($_POST['comment']));

    // Basic validation (make sure required fields are not empty)
    if (empty($name) || empty($email) || empty($comment)) {
        $error = "Please fill out all required fields (Name, Email, and Comment).";
    } else {
        // Prepare an SQL query to insert the data into the database
        $stmt = $conn->prepare("INSERT INTO contact (name, email, gym, comment) VALUES (?, ?, ?, ?)");
        $stmt->bind_param("ssss", $name, $email, $gym, $comment);

        // Execute the statement
        if ($stmt->execute()) {
            $success = "Form submitted successfully!";
        } else {
            $error = "Error: " . $stmt->error;
        }

        // Close the statement
        $stmt->close();
    }
}

// Close the database connection
$conn->close();
